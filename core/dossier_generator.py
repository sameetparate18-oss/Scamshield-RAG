"""
ScamShield-RAG :: Automated Forensic Dossier & Statutory Notice Generator
Compiles court-admissible technical evidence and Section 94 BNSS requisition orders.
"""

from datetime import datetime, timezone
from typing import Dict, Any


def generate_police_requisition_order(evidence_id: str, forensic_meta: Dict[str, Any]) -> str:
    """
    Generates a pre-filled statutory notice for Law Enforcement Officers
    to serve to Bank Nodal Officers and Telecom Providers under Section 94 BNSS.
    """
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    
    notice = f"""================================================================================
                    CYBER CRIME INVESTIGATION REQUISITION NOTICE
              [Under Section 94 BNSS, 2023 / Section 91 CrPC, 1973]
================================================================================
EVIDENCE ARTIFACT ID : {evidence_id}
TIMESTAMP OF INGEST  : {timestamp}
SYSTEM CLASSIFICATION: {forensic_meta.get('category', 'Cyber Fraud Incident')}
CALCULATED RISK SCORE: {forensic_meta.get('risk_score', 'N/A')} / 1.00

1. FORENSIC IDENTIFIERS EXTRACTED:
--------------------------------------------------------------------------------
• Virtual Payment Address (VPA) : {forensic_meta.get('vpa', 'N/A')}
• Payee / Account Label         : {forensic_meta.get('payee_name', 'N/A')}
• Resolved Settlement Bank      : {forensic_meta.get('acquirer_bank', 'N/A')}
• Suspect URLs / Domains        : {', '.join(forensic_meta.get('urls', [])) or 'None'}
• Phone Numbers Extracted       : {', '.join(forensic_meta.get('phones', [])) or 'None'}

2. CRYPTOGRAPHIC CHAIN OF CUSTODY (BSA COMPLIANCE):
--------------------------------------------------------------------------------
• Primary Digest (SHA-256)      : {forensic_meta.get('sha256', 'N/A')}
• Secondary Digest (MD5)        : {forensic_meta.get('md5', 'N/A')}
• Evidentiary Integrity Status  : SEALED & TAMPER-EVIDENT

3. STATUTORY PRODUCTION DIRECTIVE TO INTERMEDIARY:
--------------------------------------------------------------------------------
To: Nodal Officer / Authorized Legal Process Specialist,
    {forensic_meta.get('acquirer_bank', 'Concerned Financial Entity / Telecom Provider')}

You are hereby directed under statutory authority to furnish the following records
associated with the above-referenced identifiers within 24 hours:
  (a) Complete KYC application form, identity proof, and verified physical address.
  (b) Account statement from inception to date with IP logs for internet banking.
  (c) Associated device identifiers (MAC address, IMEI, registered mobile numbers).
  (d) Direction to immediately freeze / place a debit lien on beneficiary balances.

Generated by ScamShield-RAG Cyber Forensic Workstation.
================================================================================
"""
    return notice