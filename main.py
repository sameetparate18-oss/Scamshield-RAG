def local_qr_analyzer(raw_data: str) -> dict:
    """Forensically breaks down an Indian UPI or Quishing payload."""
    raw = (raw_data or "").strip()
    if not raw:
        return {"type": "EMPTY", "status": "INVALID", "calculated_risk": 0.0, "anomalies": ["Empty payload."]}

    if raw.startswith("http://") or raw.startswith("https://"):
        return {
            "type": "QUISHING_WEB_URL",
            "is_upi": False,
            "raw_payload": raw,
            "status": "CRITICAL_RISK",
            "calculated_risk": 0.95,
            "anomalies": [
                "QR resolves to a Web URL, NOT an NPCI UPI payment channel.",
                "High probability of credential harvesting or web phishing."
            ],
            "recommendation": "DO NOT PROCEED. Verify website certificate."
        }

    if not raw.startswith("upi://pay"):
        return {
            "type": "NON_PAYMENT_QR",
            "is_upi": False,
            "raw_payload": raw,
            "status": "BENIGN_OR_OTHER",
            "calculated_risk": 0.10,
            "anomalies": ["Standard NPCI 'upi://pay' header not found."],
            "recommendation": "Generic QR code (Wi-Fi, plain text, or contact card)."
        }

    parsed = urllib.parse.urlparse(raw)
    params = urllib.parse.parse_qs(parsed.query)

    vpa = params.get("pa", [""])[0]
    name = params.get("pn", [""])[0]
    mcc = params.get("mc", [""])[0]
    amount = params.get("am", [""])[0]
    currency = params.get("cu", ["INR"])[0]

    handle = vpa.split("@")[-1].lower() if "@" in vpa else ""
    bank_info = PSP_BANK_MAP.get(handle, {
        "bank": "Unlisted Co-op / Private Switch",
        "provider": "Custom Third-Party"
    })

    anomalies = []
    risk_score = 0.0

    if handle not in PSP_BANK_MAP:
        anomalies.append(f"Unregistered or private PSP handle (@{handle}).")
        risk_score += 0.35

    if amount and float(amount or 0) > 0:
        anomalies.append(f"Static debit charge of ₹{amount} pre-locked in QR.")
        risk_score += 0.20

    flagged_terms = ["lottery", "cashback", "refund", "police", "customs", "cbi", "tax"]
    if any(term in name.lower() for term in flagged_terms):
        anomalies.append("Payee name mimics official legal or monetary authority.")
        risk_score += 0.45

    risk_score = min(1.0, round(risk_score, 2))
    status = "LIKELY_SCAM" if risk_score >= 0.55 else ("SUSPICIOUS" if risk_score >= 0.30 else "VERIFIED_STRUCTURE")

    return {
        "type": "UPI_PAYMENT",
        "is_upi": True,
        "vpa": vpa,
        "declared_name": name or "Not Declared",
        "banking_partner": bank_info["bank"],
        "psp_application": bank_info["provider"],
        "merchant_code": mcc or "P2P / Individual",
        "currency": currency,
        "amount_locked": f"₹{amount}" if amount else "Dynamic / User-entered",
        "anomalies": anomalies or ["Standard compliant NPCI UPI format."],
        "calculated_risk": risk_score,
        "status": status,
        "raw_payload": raw
    }


