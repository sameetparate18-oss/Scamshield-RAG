    def _run_analysis(self):
        if not self.engine:
            messagebox.showwarning("Engine Standby", "Verdict Engine is still loading vectors.")
            return

        is_text = "Raw" in self.tabs.get()
        if is_text:
            text = self.txt_evidence.get("1.0", "end").strip()
            if not text:
                messagebox.showwarning("Input Required", "Enter textual communication or logs.")
                return
            mode, payload = "text", text
        else:
            if not self.selected_file_path:
                messagebox.showwarning("Artifact Required", "Stage an evidence file first.")
                return
            mode, payload = "file", self.selected_file_path

        self.btn_analyze.configure(state="disabled")
        self.pipeline_box.grid(row=3, column=0, sticky="ew", pady=(10, 0))
        self.lbl_pipeline_step.configure(text="Pipeline: Extracting Tokens...", text_color=THEME["accent"])

        def _worker():
            try:
                t0 = time.time()
                res = ingest_text(payload) if mode == "text" else ingest_auto(payload)
                t1 = time.time()

                if not getattr(res, "success", False):
                    raise ValueError(getattr(res, "error", "Ingestion failed."))

                extracted = getattr(res, "extracted_text", "").strip()
                if not extracted:
                    raise ValueError("No machine-readable tokens extracted from artifact.")

                self.after(0, lambda: self.lbl_pipeline_step.configure(text="Pipeline: Vector RAG Retrieval..."))

                t2 = time.time()
                verdict = self.engine.analyze(extracted)
                t3 = time.time()

                elapsed = {"ingest": round(t1 - t0, 2), "analysis": round(t3 - t2, 2), "total": round(t3 - t0, 2)}
                disp = payload if mode == "text" else os.path.basename(payload)
                self.after(0, lambda: self._on_scan_success(verdict, res, disp, elapsed))
            except Exception as e:
                err = str(e)
                traceback.print_exc()
                self.after(0, lambda: self._on_scan_fault(err))

        threading.Thread(target=_worker, daemon=True).start()

    def _on_scan_fault(self, err):
        self.pipeline_box.grid_forget()
        self.btn_analyze.configure(state="normal")
        messagebox.showerror("Pipeline Failure", f"Forensic scan could not be completed:\n{err}")

