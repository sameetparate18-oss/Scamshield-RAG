    def _qr_toggle_camera(self):
        if not HAS_CV2:
            messagebox.showwarning("OpenCV Missing", "Live scanning requires opencv-python:\npip install opencv-python")
            return

        if self.camera_running:
            self.camera_running = False
            self.lbl_qr_camera_status.configure(text="Sensor State: Idle", text_color=THEME["text_dim"])
            return

        self.camera_running = True
        self.lbl_qr_camera_status.configure(text="Sensor State: Active (Press 'q' in camera feed to cancel)", text_color=THEME["safe"])

        def _cam_worker():
            cap = cv2.VideoCapture(0)
            detector = cv2.QRCodeDetector()
            while self.camera_running and cap.isOpened():
                ret, frame = cap.read()
                if not ret:
                    break

                payload, _, _ = detector.detectAndDecode(frame)
                if payload:
                    self.camera_running = False
                    cap.release()
                    cv2.destroyAllWindows()
                    self.after(0, lambda p=payload: self._on_webcam_found(p))
                    return

                cv2.imshow("ScamShield - QR Optical Sensor (Press Q to exit)", frame)
                if cv2.waitKey(1) & 0xFF == ord('q'):
                    break

            cap.release()
            cv2.destroyAllWindows()
            self.camera_running = False
            self.after(0, lambda: self.lbl_qr_camera_status.configure(text="Sensor State: Idle", text_color=THEME["text_dim"]))

        threading.Thread(target=_cam_worker, daemon=True).start()

