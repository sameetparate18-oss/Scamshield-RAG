    def _qr_upload_file(self):
        if not HAS_CV2:
            messagebox.showwarning("OpenCV Missing", "Install OpenCV for image scanning:\npip install opencv-python")
            return
        path = filedialog.askopenfilename(filetypes=[("Image Files", "*.png *.jpg *.jpeg *.webp *.bmp")])
        if not path:
            return
        try:
            with open(path, "rb") as f:
                bytes_arr = bytearray(f.read())
                np_arr = np.asarray(bytes_arr, dtype=np.uint8)
                img = cv2.imdecode(np_arr, cv2.IMREAD_COLOR)

            detector = cv2.QRCodeDetector()
            payload, _, _ = detector.detectAndDecode(img)

            if not payload:
                gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
                payload, _, _ = detector.detectAndDecode(gray)

            if not payload:
                messagebox.showinfo("No QR Detected", "No readable QR code found in selected image.")
                return

            res = local_qr_analyzer(payload)
            self._render_qr_dossier(res)
        except Exception as e:
            messagebox.showerror("Parsing Failure", f"Could not inspect artifact:\n{e}")

