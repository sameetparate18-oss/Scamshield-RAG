    def _qr_upload_file(self):
        if not HAS_CV2:
            messagebox.showwarning("OpenCV Missing", "Install OpenCV for image scanning:\npip install opencv-python")
            return
        path = filedialog.askopenfilename(filetypes=[("Image Files", "*.png *.jpg *.jpeg *.webp *.bmp")])
        if not path:
            return
        try:
            with open(path, "rb") as f:
                bytes_arr = bytearray(f.read())
                np_arr = np.asarray(bytes_arr, dtype=np.uint8)
                img = cv2.imdecode(np_arr, cv2.IMREAD_COLOR)

            detector = cv2.QRCodeDetector()
            payload, _, _ = detector.detectAndDecode(img)

            if not payload:
                gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
                payload, _, _ = detector.detectAndDecode(gray)

            if not payload:
                messagebox.showinfo("No QR Detected", "No readable QR code found in selected image.")
                return

            res = local_qr_analyzer(payload)
            self._render_qr_dossier(res)
        except Exception as e:
            messagebox.showerror("Parsing Failure", f"Could not inspect artifact:\n{e}")

    def _qr_toggle_camera(self):
        if not HAS_CV2:
            messagebox.showwarning("OpenCV Missing", "Live scanning requires opencv-python:\npip install opencv-python")
            return

        if self.camera_running:
            self.camera_running = False
            self.lbl_qr_camera_status.configure(text="Sensor State: Idle", text_color=THEME["text_dim"])
            return

        self.camera_running = True
        self.lbl_qr_camera_status.configure(text="Sensor State: Active (Press 'q' in feed to cancel)", text_color=THEME["safe"])

        def _cam_worker():
            cap = cv2.VideoCapture(0)
            detector = cv2.QRCodeDetector()
            while self.camera_running and cap.isOpened():
                ret, frame = cap.read()
                if not ret:
                    break

                payload, _, _ = detector.detectAndDecode(frame)
                if payload:
                    self.camera_running = False
                    cap.release()
                    cv2.destroyAllWindows()
                    self.after(0, lambda p=payload: self._on_webcam_found(p))
                    return

                cv2.imshow("ScamShield - QR Scanner (Press Q to exit)", frame)
                if cv2.waitKey(1) & 0xFF == ord('q'):
                    break

            cap.release()
            cv2.destroyAllWindows()
            self.camera_running = False
            self.after(0, lambda: self.lbl_qr_camera_status.configure(text="Sensor State: Idle", text_color=THEME["text_dim"]))

        threading.Thread(target=_cam_worker, daemon=True).start()

    def _on_webcam_found(self, payload: str):
        self.lbl_qr_camera_status.configure(text="QR Captured Successfully", text_color=THEME["accent"])
        res = local_qr_analyzer(payload)
        self._render_qr_dossier(res)

