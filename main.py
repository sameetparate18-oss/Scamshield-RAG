        if os.path.exists(HISTORY_FILE):
            try:
                with open(HISTORY_FILE, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    return data[-MAX_RECORDS:] if isinstance(data, list) else []
            except Exception:
                pass
        return []

